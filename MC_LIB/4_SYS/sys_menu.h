/* 无：菜单模块内部状态全部为文件私有（static），外部通过接口函数访问 */


/*-------------------------- 5. 接口函数声明 ------------------------------*/

/*
Function: Menu_Init
Description:
    菜单系统初始化。在 main() 开头调用一次。
    内部完成：
        - 菜单内部状态清零
        - 各参数恢复默认值（默认模式、转速、时间、气压等）
        - 页面切换到主页面
Input:  无
Output: 无
Return: 无
Author: CJYS
*/
void Menu_Init(void);

/*
Function: Menu_Loop_10ms
Description:
    菜单 10ms 周期任务。必须每 10ms 调用一次。
    内部完成：
        1. 按键扫描（带软件消抖）
        2. 每 1 秒累加运行时间，检测报警
        3. 按需刷新 LCD（整屏或局部）
Input:  无
Output: 无
Return: 无
Author: CJYS
*/
void Menu_Loop_10ms(void);


#endif /* SYS_MENU_H */
