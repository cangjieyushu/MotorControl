void scroll_task_10ms(void)
{
    for (uint8_t n = 0; n < s_scroll_count; n++) {
        scroll_t *s = &s_scroll[n];
        if (s->len == 0) continue;

        for (uint8_t i = 0; i < s->rows_per_tick; i++) {
            render_line_row(s, s->cur_row);
            lcd_cache_flush();

            s->cur_row++;
            if (s->cur_row >= HZ_SCROLL_H) {
                s->cur_row = 0;
                s->scroll_offset--;
                if (s->scroll_offset < -s->text_width)
                    s->scroll_offset = LCD_WIDTH;
                break;
            }
        }
    }
}

