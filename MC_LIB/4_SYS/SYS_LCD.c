/*====================== 全局变量 ======================*/
static volatile uint8_t lcd_dma_done = 1;
static uint16_t lcd_cache[LCD_CACHE_LINES * LCD_CACHE_WIDTH];
static uint16_t lcd_cache_y_start = 0;
static uint8_t  lcd_cache_dirty   = 0;

/*====================== 延时 ======================*/
static void delay_ms(uint32_t ms)
{
    for (uint32_t i = 0; i < ms; i++)
        for (volatile uint32_t j = 0; j < 8000; j++);
}

/*====================== SPI 阻塞写一个字节 ======================*/
static uint8_t spi_rw_byte(uint8_t data)
{
    while (RESET == spi_i2s_flag_get(HAL_MOTOR_SPI, SPI_FLAG_TBE));
    spi_i2s_data_transmit(HAL_MOTOR_SPI, data);
    while (RESET == spi_i2s_flag_get(HAL_MOTOR_SPI, SPI_FLAG_RBNE));
    return (uint8_t)spi_i2s_data_receive(HAL_MOTOR_SPI);
}

/*====================== DMA 中断 ======================*/
/*=====================================================================
 * DMA 中断：当一帧数据发送完毕，硬件自动进这个函数
 * 我们需要把 lcd_dma_done 置 1，通知上层"发送完成了"
 *=====================================================================*/
void DMA_Channel1_2_IRQHandler(void)
{
    /* 判断是不是"传输完成"中断 */
    if (dma_interrupt_flag_get(HAL_SPI_TX_DMA_CH, DMA_INT_FLAG_FTF) == SET) {
        dma_interrupt_flag_clear(HAL_SPI_TX_DMA_CH, DMA_INT_FLAG_FTF);
        lcd_dma_done = 1;   /* 标记 DMA 空闲 */
    }
}

void lcd_dma_wait(void)
{
    while (!lcd_dma_done);
}

/*=====================================================================
 * 用 DMA 发送一块数据（阻塞版本）
 * 参数：data=数据首地址；len=字节数
 * 特点：函数返回时数据一定发完了（内部 while 等标志）
 *=====================================================================*/
void lcd_dma_send_block(const uint8_t *data, uint32_t len)
{
    if (len == 0) return;           /* 长度 0 直接返回 */

    lcd_dma_done = 0;               /* 先标记 DMA 忙 */

    dma_channel_disable(HAL_SPI_TX_DMA_CH);     /* 关通道，准备配置 */
    dma_memory_address_config(HAL_SPI_TX_DMA_CH, (uint32_t)data);  /* 源地址 */
    dma_transfer_number_config(HAL_SPI_TX_DMA_CH, len);            /* 传输字节数 */
    dma_flag_clear(HAL_SPI_TX_DMA_CH, DMA_FLAG_FTF);               /* 清完成标志 */
    dma_channel_enable(HAL_SPI_TX_DMA_CH);                         /* 开通道，开始传 */

    while (!lcd_dma_done);          /* 等中断把 lcd_dma_done 置 1 */
}

void lcd_dma_send_bytes(const uint8_t *data, uint32_t len)
{
    while (len > 0) {
        uint32_t chunk = (len > LCD_CACHE_SIZE) ? LCD_CACHE_SIZE : len;
        lcd_dma_send_block(data, chunk);
        data += chunk;
        len  -= chunk;
    }
}

/*====================== 命令/数据 ======================*/
void lcd_write_cmd(uint8_t cmd)
{
    lcd_dma_wait();
    LCD_DC_CMD();
    LCD_CS_LOW();
    spi_rw_byte(cmd);
    LCD_CS_HIGH();
}

void lcd_write_data(uint8_t data)
{
    lcd_dma_wait();
    LCD_DC_DATA();
    LCD_CS_LOW();
    spi_rw_byte(data);
    LCD_CS_HIGH();
}

