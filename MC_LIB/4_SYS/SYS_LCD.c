/*====================== 缓存 ======================*/
void lcd_cache_init(void)
{
    uint32_t total = LCD_CACHE_LINES * LCD_CACHE_WIDTH;
    for (uint32_t i = 0; i < total; i++) lcd_cache[i] = 0;
    lcd_cache_y_start = 0;
    lcd_cache_dirty   = 0;
}

void lcd_cache_begin(uint16_t y_start)
{
    lcd_cache_y_start = y_start;
    lcd_cache_dirty   = 0;
}

void lcd_cache_set_pixel(uint16_t x, uint16_t y, uint16_t color)
{
    if (x >= LCD_WIDTH) return;
    if (y < lcd_cache_y_start ||
        y >= lcd_cache_y_start + LCD_CACHE_LINES) return;
    uint16_t row = y - lcd_cache_y_start;
    lcd_cache[row * LCD_CACHE_WIDTH + x] = color;
    lcd_cache_dirty = 1;
}

void lcd_cache_fill(uint16_t color)
{
    uint32_t total = LCD_CACHE_LINES * LCD_CACHE_WIDTH;
    for (uint32_t i = 0; i < total; i++) lcd_cache[i] = color;
    lcd_cache_dirty = 1;
}

void lcd_cache_flush(void)
{
    if (!lcd_cache_dirty) return;
    lcd_set_window(0, lcd_cache_y_start,
                   LCD_WIDTH - 1,
                   lcd_cache_y_start + LCD_CACHE_LINES - 1);
    LCD_DC_DATA();
    LCD_CS_LOW();
    lcd_dma_send_block((const uint8_t *)lcd_cache, LCD_CACHE_SIZE);
    LCD_CS_HIGH();
    lcd_cache_dirty = 0;
}

/*====================== 全屏填充 ======================*/
void lcd_fill_color(uint16_t color)
{
    uint32_t total = LCD_CACHE_LINES * LCD_CACHE_WIDTH;
    for (uint32_t i = 0; i < total; i++) lcd_cache[i] = color;

    lcd_set_window(0, 0, LCD_WIDTH - 1, LCD_HEIGHT - 1);

    LCD_DC_DATA();
    LCD_CS_LOW();
    uint32_t bytes = (uint32_t)LCD_WIDTH * LCD_HEIGHT * 2;
    while (bytes > 0) {
        uint32_t chunk = (bytes > LCD_CACHE_SIZE) ? LCD_CACHE_SIZE : bytes;
        lcd_dma_send_block((const uint8_t *)lcd_cache, chunk);
        bytes -= chunk;
    }
    LCD_CS_HIGH();
}

/*====================== 矩形填充 ======================*/
void lcd_fill_rect(uint16_t x, uint16_t y, uint16_t w, uint16_t h, uint16_t color)
{
    if (x >= LCD_WIDTH || y >= LCD_HEIGHT) return;
    if (x + w > LCD_WIDTH)  w = LCD_WIDTH  - x;
    if (y + h > LCD_HEIGHT) h = LCD_HEIGHT - y;
    if (w == 0 || h == 0) return;

    for (uint16_t r = 0; r < LCD_CACHE_LINES; r++)
        for (uint16_t c = 0; c < w; c++)
            lcd_cache[r * LCD_CACHE_WIDTH + c] = color;

    lcd_set_window(x, y, x + w - 1, y + h - 1);
    LCD_DC_DATA();
    LCD_CS_LOW();

    uint16_t rows_done = 0;
    while (rows_done < h) {
        uint16_t rows_this = h - rows_done;
        if (rows_this > LCD_CACHE_LINES) rows_this = LCD_CACHE_LINES;
        uint32_t bytes = (uint32_t)rows_this * w * 2;
        lcd_dma_send_block((const uint8_t *)lcd_cache, bytes);
        rows_done += rows_this;
    }
    LCD_CS_HIGH();
}

